function renderMission(n) {
  current = n;
  updateTop();
  const m = missions[n];
  const wasCompleted = completed[n];

  game.innerHTML = `
    <div class="eyebrow">${m.label}</div>
    <h2>${m.title}</h2>
    <p>${m.intro}</p>
    ${n === 1 ? `<div class="note"><span class="pink">PERSONAL MEMORY FILE</span><br>${escapeHTML(specialMemory)}</div>` : ""}
    <div class="rule"></div>
    <p><strong>${m.question}</strong></p>
    <div id="choices">
      ${m.choices.map((c, i) => `
        <button class="btn" onclick="answer(${n},${i})">${c[0]}</button>
      `).join("")}
    </div>
    <div id="feedback" class="feedback">${wasCompleted ? "MISSION ALREADY CLEARED. You can replay it!" : ""}</div>
    <p class="small" id="heartStatus">Hidden hearts collected: ${hearts.size}/3</p>
    ${heartButton(n)}
    <div id="nextArea">
      ${wasCompleted ? nextButton(n) : ""}
    </div>`;
}

function nextButton(n) {
  const label = n < 2 ? "NEXT MISSION →" : "ENTER FINAL MISSION →";
  const action = n < 2 ? `renderMission(${n + 1})` : "renderFinalBoss()";
  return `<button class="btn primary" onclick="${action}">${label}</button>`;
}

function answer(n, i) {
  const m = missions[n];
  const correct = m.choices[i][1];
  const feedback = document.getElementById("feedback");

  if (!correct) {
    feedback.style.color = "#ffb1b1";
    feedback.textContent = m.wrong;
    return;
  }

  completed[n] = true;
  updateTop();
  feedback.style.color = "var(--green)";
  feedback.textContent = m.right;

  document.querySelectorAll("#choices .btn").forEach(button => {
    button.disabled = true;
    button.style.opacity = ".65";
  });

  document.getElementById("nextArea").innerHTML = nextButton(n);
}

