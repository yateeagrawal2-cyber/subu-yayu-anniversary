function chooseFinal(choice) {
  selectedFinal = true;
  completed[3] = true;
  updateTop();

  const feedback = document.getElementById("finalFeedback");
  feedback.textContent = "FINAL CHOICE LOCKED: " + choice + ".";
  feedback.style.color = "var(--green)";

  const allMissions = completed.every(Boolean);
  const allHearts = hearts.size === 3;

  const area = document.getElementById("finalArea");

  if (allMissions && allHearts) {
    area.innerHTML = `
      <div class="rule"></div>
      <p class="pink"><strong>ALL MISSIONS CLEARED. ALL HEARTS COLLECTED.</strong></p>
      <button class="btn primary" onclick="renderSecretEnding()">UNLOCK SECRET ENDING ♡</button>`;
  } else {
    area.innerHTML = `
      <div class="rule"></div>
      <div class="note">
        <strong>SECRET ENDING STILL LOCKED</strong><br>
        Missions cleared: ${progressCount()}/4<br>
        Hidden hearts collected: ${hearts.size}/3<br><br>
        You need every mission cleared AND all three hearts.
        Revisit the earlier levels to find what you're missing.
      </div>
      <button class="btn" onclick="renderMission(0)">REVISIT MISSION 01</button>
      <button class="btn" onclick="renderMission(1)">REVISIT MISSION 02</button>
      <button class="btn" onclick="renderMission(2)">REVISIT MISSION 03</button>
      <button class="btn primary" onclick="renderFinalBoss()">RETURN TO FINAL BOSS</button>`;
  }
}

