const game = document.getElementById("game");
const counter = document.getElementById("counter");
const bar = document.getElementById("bar");

let current = -1;
let completed = [false, false, false, false];
let hearts = new Set();
let selectedFinal = false;

function escapeHTML(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function progressCount() {
  return completed.filter(Boolean).length;
}

function updateTop() {
  const count = progressCount();
  counter.textContent = current < 0
    ? "READY TO DEPLOY"
    : current === 4
      ? "SECRET ENDING"
      : "MISSION " + String(current + 1).padStart(2, "0") + " / 04";

  bar.style.width = (count / 4 * 100) + "%";
}


function heartButton(id) {
  const found = hearts.has(id);
  return `<button
    class="heart ${found ? "found" : ""}"
    style="display:block; margin:20px auto; width:64px; height:64px; font-size:40px; color:#ff4f9a; background:#ffe0ef; border:2px solid #ff4f9a; border-radius:50%; cursor:pointer;"
    title="Collect your hidden heart"
    aria-label="Collect hidden heart ${id + 1}"
    onclick="collectHeart(${id})">
    ${found ? "♥" : "♡"}
  </button>`;
}

function collectHeart(id) {
  if (hearts.has(id)) return;
  hearts.add(id);
  renderMission(current);
  const status = document.getElementById("heartStatus");
  if (status) status.textContent = `Hidden hearts collected: ${hearts.size}/3 ♡`;
}

function startGame() {
  current = -1;
  completed = [false, false, false, false];
  hearts = new Set();
  selectedFinal = false;
  renderIntro();
}

